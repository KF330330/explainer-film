// B2 · 曲线① 抬头到 40 年（口播第 3–4 句）。相机不动（沿用 B1 的坐标系机位，不推近线头再拉回）。
// 每个十年同一个顺序：线长到 → 点上打墨点 → 横轴刻度与「N 年」 → 数字从空白滚进来、在那句念完时落定。
// 「再往后，线开始抬头」→ 曲线① 从 10 年长到 20 年（×2 落定后就接着长）；「二十年」→ 20 年刻度；「4 倍」→ 点右下 ×4 落定；
// 落定后线接着长到 30 年，「三十年」刻度、「8 倍」×8 同样落定。
// 「四十年」→ 线长到 40 年；「同样的」→ 40 年刻度；「7%」→ 「每年 7%」下面一道墨色下划线；「15 倍」→ 线头右边 ×15（字号放大 1.3 倍）落定。
// 7% 的数字都写在曲线下方（曲线与横轴之间）：曲线② 后面整条在曲线① 上方，不会压到它们。
